def get_xun_head(gan: str, zhi: str) -> str:
    """获取干支所在旬的旬头（甲X）"""
    g_idx = TIAN_GAN.index(gan)
    z_idx = DI_ZHI.index(zhi)
    offset = g_idx  # 天干距离甲的步数
    head_zhi_idx = (z_idx - offset) % 12
    return f"甲{DI_ZHI[head_zhi_idx]}"

def get_kong_wang(day_gan: str, day_zhi: str) -> list[str]:
    """根据日柱获取旬空二支"""
    xun_head = get_xun_head(day_gan, day_zhi)
    return XUN_KONG.get(xun_head, [])


