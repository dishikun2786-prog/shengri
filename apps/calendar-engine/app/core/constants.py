# ---------- 十神 ----------

def get_ten_god(day_master: str, other_gan: str) -> str:
    """根据日主和他干推算十神"""
    if day_master == other_gan:
        return "比肩"

    dm_idx = TIAN_GAN.index(day_master)
    ot_idx = TIAN_GAN.index(other_gan)
    dm_yin_yang = dm_idx % 2  # 0阳 1阴
    ot_yin_yang = ot_idx % 2
    dm_wx = GAN_WUXING[day_master]
    ot_wx = GAN_WUXING[other_gan]

    same_polarity = dm_yin_yang == ot_yin_yang

    wx_order = ["木", "火", "土", "金", "水"]
    dm_wi = wx_order.index(dm_wx)
    ot_wi = wx_order.index(ot_wx)

    if dm_wx == ot_wx:
        return "比肩" if same_polarity else "劫财"

    sheng_wo = wx_order[(dm_wi - 1) % 5]
    if ot_wx == sheng_wo:
        return "正印" if not same_polarity else "偏印"

    wo_sheng = wx_order[(dm_wi + 1) % 5]
    if ot_wx == wo_sheng:
        return "食神" if same_polarity else "伤官"

    wo_ke = wx_order[(dm_wi + 2) % 5]
    if ot_wx == wo_ke:
        return "偏财" if same_polarity else "正财"

    ke_wo = wx_order[(dm_wi - 2) % 5]
    if ot_wx == ke_wo:
        return "正官" if not same_polarity else "七杀"

    return "未知"


